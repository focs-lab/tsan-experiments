#!/usr/bin/env python3
"""write_readme_results.py <results-root>... [--readme PATH] — put the aggregator's tables into README.md.

Replaces everything between the two markers below, so it can be re-run after every application finishes and
again for Stage B. The narrative parts of the Results section (the pilot, the probes, the open questions) live
*above* the start marker and are never touched. Several roots may be given: each becomes its own "Tables — <tag>"
section, in the order given, so a later stage (the yield A/B) does not evict the sweep's own tables.
"""
import sys, os, re

def demote(body):
    """The per-app files are standalone documents; their own '##' headings must not outrank the '####'
    section they are pasted into."""
    return re.sub(r"(?m)^(#{1,4}) ", lambda m: "#" * min(6, len(m.group(1)) + 3) + " ", body)

START = "<!-- P5-TABLES-START -->"
END = "<!-- P5-TABLES-END -->"

def section(root):
    tag = os.path.basename(root.rstrip("/"))
    parts = [f"### Tables — {tag}\n",
             f"Generated by `aggregate.py` from `results/{tag}/`; regenerate with "
             f"`python3 write_readme_results.py results/{tag}`.\n"]
    summary = os.path.join(root, "perf_summary.md")
    if os.path.exists(summary):
        body = demote(open(summary).read().split("\n", 1)[1].strip())   # drop the file's own H1
        parts += ["#### Cross-application summary\n", body, ""]
    for f in sorted(os.listdir(root)):
        m = re.fullmatch(r"perf_(\w+)\.md", f)
        if not m or m.group(1) == "summary":
            continue
        body = demote(open(os.path.join(root, f)).read().split("\n", 1)[1].strip())
        parts += [f"#### {m.group(1)}\n", body, ""]
    return parts

def main():
    argv = sys.argv[1:]
    readme = os.path.join(os.path.dirname(os.path.abspath(__file__)), "README.md")
    if "--readme" in argv:
        i = argv.index("--readme"); readme = argv[i + 1]; del argv[i:i + 2]
    roots = list(dict.fromkeys(os.path.normpath(r) for r in argv if os.path.isdir(r)))
    if not roots:
        sys.exit("write_readme_results.py: no existing results root given")
    parts = []
    for r in roots:
        parts += section(r)
    block = "\n".join(parts).rstrip() + "\n"
    t = open(readme).read()
    if START in t and END in t:
        t = t[:t.index(START) + len(START)] + "\n\n" + block + "\n" + t[t.index(END):]
    else:
        t = t.rstrip() + "\n\n" + START + "\n\n" + block + "\n" + END + "\n"
    open(readme, "w").write(t)
    print(f"README updated from {', '.join(roots)}: {sum(1 for p in parts if p.startswith('#### '))} sections")

if __name__ == "__main__":
    main()
